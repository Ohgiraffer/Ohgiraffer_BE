-- [사유]
--  요구사항의 "캘린더에 공휴일 표시".
--  공공데이터포털 특일 정보 API 를 배치로 부르는 방안이 있으나 API 키 발급을 기다려야 하고,
--  외부 장애가 캘린더를 막을 수 있다. 확정된 값이라 먼저 넣어 화면을 완성한다.
--  키가 나오면 배치를 얹되, 배치는 "없는 것만 추가" 하므로 이 시드와 충돌하지 않는다.
--
-- [Repeatable 인 이유]
--  연도를 추가할 때마다 새 버전 파일을 만들지 않기 위해서다.
--  대신 재실행되므로 넣기 전에 해당 연도를 지운다. 그냥 INSERT 만 두면
--  파일을 고칠 때마다 이미 있는 공휴일이 중복으로 쌓인다.
--
--  DELETE 범위를 연도로 좁힌 것도 그래서다. HOLIDAY 를 통째로 지우면
--  나중에 배치가 넣은 다른 연도까지 함께 날아간다.
--
-- [저장 형태]
--  calendar_event 에 그대로 넣는다. 별도 테이블을 두면 월간 조회에서
--  두 곳을 읽어 합쳐야 하고 범위·정렬 판정을 두 번 구현하게 된다.
--
--   event_type         = 'HOLIDAY'   화면은 이 값으로 날짜를 공휴일로 그린다
--   created_by         = NULL        등록자가 없어 아무도 삭제할 수 없다
--   is_all_day         = TRUE        공휴일은 항상 종일이다
--   is_auto_registered = TRUE        사람이 만든 일정과 구분한다
--   start_time         = 그날 00:00:00.000000
--   end_time           = 그날 23:59:59.999999
--
--  종료를 0시로 두면 그날 낮에 "진행 중인 일정" 을 찾을 때 이미 끝난 것으로 잡힌다.
--  일반 종일 일정과 같은 규칙으로 맞춘다.
--
-- [수록 범위]
--  2026년 19건. 대체공휴일 포함.
--  현충일(6/6 토)은 대체공휴일 대상이 아니라 대체 항목이 없다.
-- ============================================================

