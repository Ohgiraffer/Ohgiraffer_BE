-- ============================================================
-- 공지 카테고리 기본값을 프론트 화면(피그마) 기준으로 정리
-- 담당: be2 (박정민)
--
-- [사유]
--  공지 작성 화면의 카테고리 드롭다운이 수업 / 과제 / 운영 / 지원 4개다.
--  직전 마이그레이션(V20260804_1142)에서 넣은 '전체'는 목록 화면의
--  필터 탭(= 카테고리 전체 보기)으로 해석되어 작성 드롭다운에는 없다.
--
-- [처리]
--  이미 '전체'(id=1)를 참조하는 공지 행이 있을 수 있으므로 삭제하지 않고
--  이름만 '수업'으로 변경한다. FK 위반 없이 안전하게 정리된다.
--  is_default 는 드롭다운 기본 선택값을 뜻하며 '수업' 하나만 TRUE 로 둔다.
-- ============================================================

UPDATE `notice_category`
   SET `name` = '수업', `is_default` = TRUE
 WHERE `notice_category_id` = 1;

INSERT IGNORE INTO `notice_category` (`notice_category_id`, `name`, `is_default`) VALUES
    (2, '과제', FALSE),
    (3, '운영', FALSE),
    (4, '지원', FALSE);
